-- Supabase(PostgreSQL) 스키마 (수업 Chapter 14-2 STEP 2~3 구조).
-- 보안 원칙: RLS 켜고 읽기 정책만 두며, anon/authenticated 에는 SELECT 만 부여.
-- 쓰기는 서버(Make, secret key)만 수행한다.

create table if not exists public.regions (
    region_code text primary key,
    region_name text not null unique,
    center_lat double precision,
    center_lng double precision,
    created_at timestamptz not null default now()
);

create table if not exists public.naver_trend (
    id bigint generated by default as identity primary key,
    reference_date date not null,
    keyword text not null,
    ratio numeric not null,
    collected_at timestamptz not null default now(),
    unique (reference_date, keyword)
);

create table if not exists public.tourism_demand (
    id bigint generated by default as identity primary key,
    reference_date date not null,
    region_code text not null,
    stay_strength numeric,
    consumption_strength numeric,
    collected_at timestamptz not null default now(),
    unique (reference_date, region_code)
);

create table if not exists public.local_places (
    id bigint generated by default as identity primary key,
    place_key text not null unique,
    region_code text,
    search_category text not null,
    name text not null,
    category text,
    address text,
    road_address text,
    longitude double precision,
    latitude double precision,
    source_link text,
    collected_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.ai_region_analysis (
    id bigint generated by default as identity primary key,
    analysis_date date not null,
    region_code text not null,
    summary text not null,
    limitations text,
    llm_provider text,
    model_name text,
    created_at timestamptz not null default now(),
    unique (analysis_date, region_code)
);

create table if not exists public.collection_runs (
    run_id text primary key,
    source text not null,
    started_at timestamptz not null,
    finished_at timestamptz,
    status text not null,
    row_count integer not null default 0,
    error_message text,
    created_at timestamptz not null default now()
);

-- RLS + 읽기 정책
alter table public.regions            enable row level security;
alter table public.naver_trend        enable row level security;
alter table public.tourism_demand     enable row level security;
alter table public.local_places       enable row level security;
alter table public.ai_region_analysis enable row level security;
alter table public.collection_runs    enable row level security;

create policy "public read regions"            on public.regions            for select using (true);
create policy "public read naver_trend"        on public.naver_trend        for select using (true);
create policy "public read tourism_demand"     on public.tourism_demand     for select using (true);
create policy "public read local_places"       on public.local_places       for select using (true);
create policy "public read ai_region_analysis" on public.ai_region_analysis for select using (true);
create policy "public read collection_runs"    on public.collection_runs    for select using (true);

-- 권한: 공개 키는 읽기만 (가이드 외 추가 보안 조치)
revoke all on public.regions, public.naver_trend, public.tourism_demand,
              public.local_places, public.ai_region_analysis, public.collection_runs
  from anon, authenticated;
grant select on public.regions, public.naver_trend, public.tourism_demand,
                public.local_places, public.ai_region_analysis, public.collection_runs
  to anon, authenticated;
